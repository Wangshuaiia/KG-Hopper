"""Generate small synthetic SFT / RL / eval sets from the KG (enough to run the pipeline).

Questions come from 1- and 2-hop walks over the KG starting at seed entities; the gold path
is known, so SFT trajectories are written from templates and the retrieval is done with the
same two-stage KG tool the policy uses. A trajectory is kept only if the tool actually
returns the needed triple, mirroring the paper's filter for correct tool calls.

No reasoning text is generated by an LLM here: the paper's cold-start data comes from
prompting a strong LLM, and for real runs that should be an open model you are allowed to
distil from.

    python -m kghopper.build_data --config configs/local_cpu.yaml
"""
import argparse
import random
from concurrent.futures import ThreadPoolExecutor

from . import protocol
from .config import add_config_args, load_config, resolve_path
from .data import write_jsonl
from .kg import make_kg
from .kg.base import normalize_entity

DEFAULT_SEEDS = [
    "J. K. Rowling", "Albert Einstein", "Leonardo da Vinci", "The Beatles", "Marie Curie", "William Shakespeare",
    "Harvard University", "Star Wars", "Tokyo", "Apple Inc.", "Lionel Messi", "Mount Everest",
    "Charles Darwin", "The Lord of the Rings", "Wolfgang Amadeus Mozart", "Amazon River",
]


# Intermediate hops through hub-like values ("Male", "Location", ...) make odd questions.
HUB_WORDS = {"gender", "type", "types", "domain", "kind", "category", "class", "status", "instance"}


def phrase(relation):
    return relation.split(".")[-1].replace("_", " ").strip()


def usable(edges, exclude):
    """Relations with 1-3 objects, none of them an entity we came from."""
    bad = {normalize_entity(e) for e in exclude}
    return sorted(r for r, objs in edges.items() if 1 <= len(objs) <= 3 and not {normalize_entity(o) for o in objs} & bad)


def has_relation(triples, relation):
    return any(r == relation for _, r, _ in triples)


def tool_text(triples, prev):
    text = protocol.format_triples(triples)
    return text.lstrip("\n") if prev.endswith("\n\n") else text


def answer_text(objs):
    return objs[0] if len(objs) == 1 else "; ".join(objs)


def walk(seed, kg, rng):
    """Returns up to two samples (1-hop and 2-hop) for one seed entity."""
    backend = kg.backend
    out = []
    e1 = backend.neighbourhood(seed)
    rels1 = usable(e1, [seed])
    if not rels1:
        return out
    rng.shuffle(rels1)

    # 1-hop
    r1 = rels1[0]
    golds = e1[r1]
    q = f"What is the {phrase(r1)} of {seed}?"
    t1 = kg.search(seed, q)
    if has_relation(t1, r1):
        s1 = f" The question asks for the {phrase(r1)} of {seed}. I will look up {seed}. <search> {seed} </search>"
        s2 = tool_text(t1, s1)
        s3 = f"The triples show that the {phrase(r1)} of {seed} is {', '.join(golds)}. </think>\n\n<answer> {answer_text(golds)} </answer>"
        out.append({"question": q, "golds": golds, "topic_entities": [seed], "hops": 1,
                    "segments": [{"text": s1, "from_model": True}, {"text": s2, "from_model": False}, {"text": s3, "from_model": True}]})

    # 2-hop: seed -r1-> mid -r2-> answer
    for r1 in rels1[:8]:
        if len(e1[r1]) != 1 or set(phrase(r1).split()) & HUB_WORDS:
            continue
        mid = e1[r1][0]
        e2 = backend.neighbourhood(mid)
        rels2 = [r for r in usable(e2, [seed, mid]) if phrase(r) != phrase(r1)]
        if not rels2:
            continue
        r2 = rng.choice(rels2)
        golds = e2[r2]
        q = f"What is the {phrase(r2)} of the {phrase(r1)} of {seed}?"
        t1, t2 = kg.search(seed, q), kg.search(mid, q)
        if not (has_relation(t1, r1) and has_relation(t2, r2)):
            continue
        s1 = f" First I need the {phrase(r1)} of {seed}. <search> {seed} </search>"
        s2 = tool_text(t1, s1)
        s3 = f"The {phrase(r1)} of {seed} is {mid}. Next I need the {phrase(r2)} of {mid}. <search> {mid} </search>"
        s4 = tool_text(t2, s3)
        s5 = f"The {phrase(r2)} of {mid} is {', '.join(golds)}. </think>\n\n<answer> {answer_text(golds)} </answer>"
        out.append({"question": q, "golds": golds, "topic_entities": [seed], "hops": 2,
                    "segments": [{"text": s1, "from_model": True}, {"text": s2, "from_model": False},
                                 {"text": s3, "from_model": True}, {"text": s4, "from_model": False},
                                 {"text": s5, "from_model": True}]})
        break
    return out


def main():
    parser = add_config_args(argparse.ArgumentParser())
    parser.add_argument("--seeds", nargs="*", default=None, help="seed entity names (default: a built-in list)")
    args = parser.parse_args()
    cfg = load_config(args.config, args.set)
    bc = cfg.get_section("build_data")
    seeds = args.seeds or bc.get("seeds") or DEFAULT_SEEDS
    kg = make_kg(cfg.kg)
    if not hasattr(kg, "backend"):
        raise SystemExit("build_data needs an in-process KG backend (kg.backend: claude_sim or static)")

    with ThreadPoolExecutor(max_workers=cfg.kg.get("max_workers", 8)) as pool:
        per_seed = list(pool.map(lambda s: walk(s, kg, random.Random(f"{cfg.get('seed', 0)}-{s}")), seeds))

    # Split by seed entity so SFT, RL and eval questions never share a topic entity.
    n = len(seeds)
    n_sft, n_rl = round(n * bc.get("sft_fraction", 0.5)), round(n * bc.get("rl_fraction", 0.25))
    splits = {"sft": per_seed[:n_sft], "rl": per_seed[n_sft:n_sft + n_rl], "eval": per_seed[n_sft + n_rl:]}
    out_dir = bc.get("output_dir", "data/synthetic")
    for name, groups in splits.items():
        rows = []
        for group in groups:
            for s in group:
                row = {"idx": f"synthetic-{name}-{len(rows)}", "task": "qa", "source": "synthetic", **s}
                if name != "sft":
                    row.pop("segments")
                rows.append(row)
        path = resolve_path(f"{out_dir}/{name}.jsonl")
        write_jsonl(path, rows)
        print(f"{name}: {len(rows)} samples -> {path}")
    print("KG tool calls:", kg.calls, "| Claude API calls:", getattr(kg.backend, "api_calls", 0))


if __name__ == "__main__":
    main()
